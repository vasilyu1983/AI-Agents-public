#!/usr/bin/env python3
"""PreToolUse (Claude, matcher Write|Edit): deny edits to an existing lint or format config.

When a check fails, an agent can pass it by loosening the rule instead of fixing the code.
This guard denies a Write or Edit to a protected config file that already exists, and allows
its first creation. Template and rationale: skills/universal/agents-hooks/references/
hook-templates.md, "Claude: Lint and Format Config Guard".

Policy rule: a path (repo-relative or realpath, or its basename) that matches an fnmatch pattern in
policy["protected_paths"] (hooks/policy.py; default empty) is denied for Write and Edit, whether or
not the file exists, so a company can protect CI and agent-config paths. If the policy is unreadable
the guard prints one line and applies only the built-in names above (same as before the policy existed).

Missing script: the hooks.json wrapper, not this file, handles it. If the installed script is absent,
the wrapper exits 2 when the input text names a protected config file, and exits 0 otherwise.

Fails closed: unreadable input, a missing file_path or an internal error exits 2.
A policy deny exits 2 with the reason on stderr. Limit: a Bash write such as `sed -i`
passes this guard; it sees only Write and Edit.
"""
import fnmatch
import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from datetime import datetime, timezone
from pathlib import Path

PROTECTED = [
    ".eslintrc*", "eslint.config.*", ".eslintignore", ".prettierrc*",
    "prettier.config.*", ".prettierignore", "ruff.toml", ".ruff.toml",
    "biome.json", "biome.jsonc", ".flake8", ".stylelintrc*",
]


def log_block(rule: str) -> None:
    """Append one JSON line per block (no path or tool input). GUARD_BLOCK_LOG overrides the path.
    A logging failure prints one line and never changes the exit code."""
    try:
        path = Path(os.environ.get("GUARD_BLOCK_LOG") or Path(__file__).resolve().parent.parent / "telemetry" / "guard-blocks.jsonl")
        path.parent.mkdir(parents=True, exist_ok=True)
        entry = {"ts": datetime.now(timezone.utc).isoformat(timespec="seconds"), "hook": "config-guard",
                 "rule": rule, "runtime": "claude"}
        with open(path, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry) + "\n")
    except Exception as exc:
        print(f"config guard: block log failed ({type(exc).__name__})", file=sys.stderr)


def policy_protected(path: str) -> bool:
    """True if path matches policy["protected_paths"]. A PolicyError warns and returns False."""
    from policy import PolicyError, load
    try:
        patterns = load().get("protected_paths") or []
    except PolicyError:
        print("config guard: policy unreadable, protected_paths not applied", file=sys.stderr)
        return False
    if not patterns:
        return False
    root = Path(__file__).resolve().parent.parent
    cands = {os.path.basename(path)}
    for p in {os.path.abspath(path), os.path.realpath(path)}:
        cands.add(os.path.basename(p))
        for base in {root, root.resolve()}:
            try:
                cands.add(Path(p).relative_to(base).as_posix())
            except ValueError:
                pass
    if not os.path.isabs(path):
        cands.add(os.path.normpath(path).replace(os.sep, "/"))
    return any(fnmatch.fnmatch(c, pat) for c in cands for pat in patterns)


def main() -> int:
    try:
        data = json.load(sys.stdin)
        if data.get("tool_name") not in ("Write", "Edit"):
            return 0
        path = (data.get("tool_input") or {}).get("file_path") or ""
        if not path:
            log_block("config:no-file-path")
            print("config guard: no file_path in input, refusing", file=sys.stderr)
            return 2
        # Lowercase: macOS file systems usually ignore case, so .ESLintrc.json is .eslintrc.json.
        names = {os.path.basename(p).lower() for p in (path, os.path.realpath(path))}  # symlink to a config
        name = next((n for n in sorted(names) if any(fnmatch.fnmatch(n, p) for p in PROTECTED)), None)
        if name and os.path.exists(path):
            log_block("config:protected-file")
            print(f"{name} is a protected lint or format config. Fix the code so the "
                  "existing rule passes, or ask the user to change the rule. "
                  "Do not edit this file and do not disable this hook.", file=sys.stderr)
            return 2
        if policy_protected(path):
            log_block("config:policy-protected-path")
            print("config guard: this path is protected by the policy (protected_paths). "
                  "Ask the user to change it.", file=sys.stderr)
            return 2
        return 0
    except Exception as exc:  # fail closed
        log_block("config:internal-error")
        print(f"config guard: {type(exc).__name__}: {exc}, refusing", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
